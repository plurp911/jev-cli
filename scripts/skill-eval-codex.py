def assert_no_ambient_skills(result,workspace,disabled_paths=()):
    rows=result.get('data') if isinstance(result,dict) else None
    if not isinstance(rows,list) or len(rows)!=1:
        raise RuntimeError('Malformed native skill inventory; isolation refused')
    row=rows[0]
    if not isinstance(row,dict) or row.get('cwd')!=str(workspace) or not isinstance(row.get('skills'),list) or not isinstance(row.get('errors'),list):
        raise RuntimeError('Malformed native skill inventory; isolation refused')
    configured={str(Path(path).resolve()) for path in disabled_paths}
    accounted=set()
    for skill in row['skills']:
        if (not isinstance(skill,dict) or type(skill.get('enabled')) is not bool or
                not isinstance(skill.get('path'),str) or not Path(skill['path']).is_absolute()):
            raise RuntimeError('Malformed native skill metadata; isolation refused')
        if skill['enabled']:
            raise RuntimeError('Native skill metadata remains enabled; evaluation isolation refused')
        canonical=str(Path(skill['path']).resolve())
        if canonical in accounted:raise RuntimeError('Duplicate canonical native inventory path')
        accounted.add(canonical)
    for error in row['errors']:
        if (not isinstance(error,dict) or not isinstance(error.get('path'),str) or
                not isinstance(error.get('message'),str) or not error['message'].strip() or
                error['path'] not in disabled_paths):
            raise RuntimeError('Unconfigured or malformed native skill loader error; isolation refused')
        canonical=str(Path(error['path']).resolve())
        if canonical in accounted:raise RuntimeError('Duplicate canonical native inventory path')
        accounted.add(canonical)
    if accounted!=configured:
        raise RuntimeError('Native inventory does not account for every configured disabled path')
    return {'enabled':0,'disabled':len(row['skills']),'loader_errors':len(row['errors']),
            'configured_canonical_paths':len(configured),'accounted_canonical_paths':len(accounted)}


