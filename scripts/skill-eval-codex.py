class InferenceBudget:
    def __init__(self,maximum):
        self.maximum=maximum;self.rounds=0;self.open=False;self.usage_seen=set()

    def note_item(self,kind,identifier):
        if kind not in {'reasoning','dynamicToolCall','agentMessage'}:return
        if not identifier:raise RuntimeError('Model notification lacks item ID')
        if not self.open:
            self.rounds+=1;self.open=True
            if self.rounds>self.maximum:raise RuntimeError('Case max_turns exceeded')

    def note_usage(self,usage):
        # Each completed model response has a cumulative usage update. A response
        # can have no reasoning, several reasoning items, or several tool calls.
        total=usage.get('total') if isinstance(usage,dict) else None
        if not isinstance(total,dict) or not isinstance(total.get('totalTokens'),int):
            raise RuntimeError('Token usage lacks cumulative inference boundary')
        fingerprint=json.dumps(total,sort_keys=True)
        if fingerprint not in self.usage_seen:
            self.usage_seen.add(fingerprint);self.open=False


