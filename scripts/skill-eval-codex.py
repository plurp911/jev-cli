class CodexServiceError(RuntimeError):
    def __init__(self,source,details):
        self.source=source;self.details=details
        trusted=source in {'account/read','thread/start','turn/start','turn/completed','error'}
        info=details.get('codexErrorInfo') if isinstance(details,dict) else None
        message=details.get('message','') if isinstance(details,dict) else ''
        status=next((v.get('httpStatusCode') for v in info.values() if isinstance(v,dict)),None) if isinstance(info,dict) else None
        self.evaluation_blocked=trusted and (source=='account/read' or status in {401,403,429})
        if trusted and isinstance(info,str) and info in {'usageLimitExceeded','rateLimitExceeded','unauthorized'}:
            self.evaluation_blocked=True
        if trusted and isinstance(message,str) and re.match(r'^(?:Usage limit exceeded|Rate limit (?:exceeded|reached)|Unauthorized)\b',message,re.I):
            self.evaluation_blocked=True
        super().__init__('Codex service error ('+source+'): '+json.dumps(details))


