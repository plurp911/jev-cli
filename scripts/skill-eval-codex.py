def validate_usage(usage):
    fields={'totalTokens','inputTokens','outputTokens','cachedInputTokens','reasoningOutputTokens'}
    if not isinstance(usage,dict):raise RuntimeError('Completed turn lacks usage observation')
    for name in ['total','last']:
        value=usage.get(name)
        if not isinstance(value,dict) or any(type(value.get(key)) is not int or value[key]<0 for key in fields):
            raise RuntimeError('Completed turn has malformed usage observation')
        if value['cachedInputTokens']>value['inputTokens'] or value['reasoningOutputTokens']>value['outputTokens']:
            raise RuntimeError('Completed turn has inconsistent usage observation')
    if usage['total']['totalTokens']<=0 or usage['total']['outputTokens']<=0:
        raise RuntimeError('Completed answer lacks positive token usage')


def belongs_to_turn(event,thread_id,turn_id):
    method=event.get('method','')
    if not (method.startswith(('item/','turn/')) or method in {'thread/tokenUsage/updated','error','model/rerouted'}):return False
    params=event.get('params',{})
    thread=params.get('threadId');turn=params.get('turnId')
    if method in {'turn/completed','turn/started'}:turn=(params.get('turn') or {}).get('id')
    if not isinstance(thread,str) or not isinstance(turn,str):
        raise RuntimeError('Turn event lacks exact thread/turn attribution')
    return thread==thread_id and turn==turn_id


