def snapshot_manifest(directory):
    digest=hashlib.sha256();files=[]
    for path in sorted(directory.rglob('*')):
        if path.is_symlink():raise RuntimeError('Snapshot contains a symlink')
        if path.name=='__pycache__' or path.suffix in {'.pyc','.pyo'}:
            raise RuntimeError('Snapshot contains generated bytecode')
        if not path.is_file():continue
        name=path.relative_to(directory).as_posix();data=path.read_bytes()
        digest.update(name.encode('utf-8')+b'\0'+data+b'\0')
        files.append({'path':name,'sha256':hashlib.sha256(data).hexdigest(),'bytes':len(data)})
    return {'sha256':digest.hexdigest(),'hash_method':'sha256 over sorted relative path UTF-8 + NUL + file bytes + NUL','files':files}


def stage_snapshot(source,destination,readonly=True):
    shutil.copytree(source,destination,symlinks=True,ignore=shutil.ignore_patterns('__pycache__','*.pyc','*.pyo','results','.git'))
    manifest=snapshot_manifest(destination)
    if readonly:
        for path in sorted(destination.rglob('*'),reverse=True):path.chmod(path.stat().st_mode & 0o777 & ~0o222)
        destination.chmod(destination.stat().st_mode & 0o777 & ~0o222)
    return manifest


